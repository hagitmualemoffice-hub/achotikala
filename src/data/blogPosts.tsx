const SHIRIM_ORDER: string[] = [
  "olot-bi-hamon-tchushot",
  "ani-bocheret-bi",
  "yoter-tov-besheket",
  "tamuz-naomi",
  "magia-lach-chani",
  "gan-naul-shulamit",
  "isha-osnat",
  "meachorei-chani",
  "rak-mi-hodaya",
  "bein-hashvarim-shulamit",
  "ma-shlomech-chani",
  "shimcha-osnat",
  "hizdamnut-osnat",
  "chashuchim-osnat",
];

export const getPostBySlug = (slug?: string): BlogPostData =>
  blogPosts.find((p) => p.slug === slug) ?? blogPosts[0];

export const getPostsBySection = (section: BlogSection): BlogPostData[] => {
  const posts = blogPosts.filter((p) => p.section === section);
  if (section !== "shirim") return posts;
  const indexOf = (slug: string) => {
    const i = SHIRIM_ORDER.indexOf(slug);
    return i === -1 ? Number.MAX_SAFE_INTEGER : i;
  };
  return [...posts].sort((a, b) => indexOf(a.slug) - indexOf(b.slug));
};

